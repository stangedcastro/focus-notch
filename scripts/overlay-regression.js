const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'focus-notch-overlay-'));
app.setPath('userData', profile);
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show:false, width:1000, height:640, webPreferences:{ preload:path.join(__dirname, '../preload.js'), contextIsolation:true, offscreen:true, backgroundThrottling:false, autoplayPolicy:'no-user-gesture-required' } });
  win.webContents.setAudioMuted(true);
  await win.loadFile(path.join(__dirname, '../overlay.html'));
  const js = source => win.webContents.executeJavaScript(source);
  win.webContents.send('focus-init', { visual:true, sound:false });
  await pause(60);
  assert.equal(await js('introAnimation.effect.getTiming().duration'), 10000);
  const opacityAt = async time => {
    await js(`introAnimation.pause(); introAnimation.currentTime=${time}`);
    await pause(25);
    return Number(await js('getComputedStyle(focusInit).opacity'));
  };
  assert(await opacityAt(0) < .01);
  assert(await opacityAt(1800) > .99);
  assert(await opacityAt(4200) > .99);
  const fade = await opacityAt(7100);
  assert(fade > 0 && fade < 1, 'Late phase fades gradually');
  assert(await opacityAt(10000) < .01, 'Effect is gone at ten seconds');
  await opacityAt(2000);
  win.webContents.send('focus-init', null);
  const cancelDeadline = Date.now() + 2000;
  do { await pause(30); } while (Number(await js('getComputedStyle(focusInit).opacity')) >= .01 && Date.now() < cancelDeadline);
  assert.equal(await js('introAnimation'), null);
  const canceledOpacity = Number(await js('getComputedStyle(focusInit).opacity'));
  assert(canceledOpacity < .01, 'Cancel fades out: '+JSON.stringify(await js('({opacity:getComputedStyle(focusInit).opacity,animations:focusInit.getAnimations().map(a=>({time:a.currentTime,state:a.playState,timing:a.effect.getTiming()}))})')));
  win.webContents.send('focus-init', { visual:false, sound:true });
  await pause(200);
  assert.equal(await js('audioContext.state'), 'running', 'Overlay audio starts without stealing focus');
  assert.equal(await js('introAnimation'), null, 'Sound-only does not show vignette');
  win.webContents.send('focus-init', null);
  await pause(50);
  assert.equal(await js('cueGain'), null, 'Cancel stops cue');
  await win.webContents.debugger.attach('1.3');
  await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features:[{ name:'prefers-reduced-motion', value:'reduce' }] });
  win.webContents.send('focus-init', { visual:true, sound:false });
  await pause(50);
  assert.equal(await js('introAnimation.effect.getKeyframes()[1].opacity'), '0.6', 'Reduced motion uses gentler opacity without movement');
  assert.equal(await js('getComputedStyle(focusInit).pointerEvents'), 'none', 'Overlay never captures input');
  console.log('OVERLAY PASS: ten-second fade, cancellation, independent sound, autoplay, reduced motion and click-through. Audio output muted for tests.');
  app.quit();
}).catch(error => { console.error(error); app.exit(1); });
app.on('will-quit', () => fs.rmSync(profile, { recursive:true, force:true }));
